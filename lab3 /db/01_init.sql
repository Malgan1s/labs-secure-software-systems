-- Скрипт 1 из 4. Выполняется первым при первом запуске контейнера базы,
-- от имени администратора postgres, в служебной базе postgres.
-- Строки, начинающиеся с двух дефисов, — комментарии SQL.

-- 1. Создаём базу данных автосервиса с русской локалью (как в заданиях 1 и 2).
--    TEMPLATE template0 — создать базу из «чистого» шаблона: свою кодировку
--    и локаль можно задать только при создании из template0.
--    ENCODING 'UTF8' — кодировка текста, кириллица хранится без проблем.
--    LOCALE 'ru_RU.UTF-8' — русские правила сортировки и сравнения строк
--    (локаль создаётся в db/Dockerfile).
CREATE DATABASE appdb
    TEMPLATE template0
    ENCODING 'UTF8'
    LOCALE 'ru_RU.UTF-8';

-- 2. Создаём пользователя для приложения.
--    Это НЕ администратор: не суперпользователь и не владелец базы.
--    Пароль учебный и лежит здесь открытым текстом только для демонстрации.
--    В настоящей системе пароли в репозитории не хранят.
CREATE USER app_user WITH PASSWORD 'app_demo_password';

-- 3. Запрещаем всем подключаться к базе, разрешаем только app_user.
--    PUBLIC — это «все пользователи сразу». По умолчанию у PUBLIC есть право
--    подключаться к любой базе, поэтому его сначала отбираем, а потом выдаём
--    право CONNECT только нашему пользователю.
REVOKE ALL ON DATABASE appdb FROM PUBLIC;
GRANT CONNECT ON DATABASE appdb TO app_user;

-- 4. К служебным базам по умолчанию может подключиться любой пользователь.
--    Закрываем: app_user должен видеть только appdb.
REVOKE CONNECT ON DATABASE postgres, template1 FROM PUBLIC;
